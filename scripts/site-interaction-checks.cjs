const fs = require('node:fs')
const assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const runtime = createRequire(`${process.env.CALKILO_QA_RUNTIME}/package.json`)
const { chromium } = runtime('playwright')
const base = process.env.CALKILO_QA_URL || 'http://localhost:4173'
const dir = 'reports/ux-2026-09-13'
;(async()=>{
const browser=await chromium.launch({channel:'chrome',headless:true})
const context=await browser.newContext({reducedMotion:'reduce'})
await context.route(/google-analytics|googletagmanager/,r=>r.abort())
const page=await context.newPage()
const checks=[]
const check=(name,value)=>{assert.ok(value,name);checks.push({name,passed:true})}
await page.setViewportSize({width:390,height:844})
await page.goto(base+'/fa/')
await page.evaluate(()=>document.fonts.ready)
check('Vazir font loads',await page.evaluate(()=>document.fonts.check('17px Vazir')))
await page.locator('.lp-menu-toggle').click()
check('Mobile menu opens',await page.locator('#mobile-navigation').isVisible())
await page.keyboard.press('Escape')
check('Escape closes menu and restores focus',await page.locator('.lp-menu-toggle').evaluate(el=>el.getAttribute('aria-expanded')==='false'&&el===document.activeElement))
await page.locator('.lp-topbar-actions a').click()
await page.waitForTimeout(100)
check('Download anchor clears header',await page.locator('#download').evaluate(el=>el.getBoundingClientRect().top>=document.querySelector('header').getBoundingClientRect().bottom-2))
await page.goto(base+'/fa/calories/')
await page.locator('#food-search').fill('قورمه')
check('Persian search finds one dish',await page.locator('.food-directory-card').count()===1)
await page.locator('.food-directory-card').click()
await page.locator('#portion-grams').fill('۲۵۰')
check('Persian digits calculate portion',await page.locator('#portion-result').innerText()==='۴۵۰ کیلوکالری تخمینی')
await page.locator('#portion-grams').fill('-10')
check('Negative portions rejected',await page.locator('#portion-grams').getAttribute('aria-invalid')==='true')
await page.locator('#portion-grams').fill('')
check('Empty portion rejected',await page.locator('#portion-grams').getAttribute('aria-invalid')==='true')
await page.locator('#portion-grams').fill('١٢٥٫٥')
check('Arabic digits and decimal accepted',await page.locator('#portion-grams').getAttribute('aria-invalid')==='false')
await page.goto(base+'/fa/calories/')
await page.locator('#food-category').selectOption('پلو')
check('Food category filters',await page.locator('.food-directory-card').count()===8)
await page.locator('#food-search').fill('zzzzz')
check('No-results guidance appears',await page.getByRole('heading',{name:'غذایی پیدا نشد'}).isVisible())
await page.getByRole('button',{name:'نمایش همه غذاها'}).click()
check('Reset restores every dish',await page.locator('.food-directory-card').count()===37)
await page.locator('#food-sort').selectOption('calories')
check('Calorie sorting works',(await page.locator('.food-directory-card h2').first().innerText())==='آش جو')
await page.goto(base+'/bmi-calculator/')
await page.getByRole('spinbutton',{name:'Height cm'}).fill('170')
await page.getByRole('spinbutton',{name:'Weight kg'}).fill('68')
await page.getByRole('button',{name:'Calculate BMI',exact:true}).click()
check('BMI 68 kg / 170 cm = 23.5',(await page.locator('.lp-bmi-result').innerText()).includes('23.5'))
await page.goto(base+'/calorie-calculator/')
await page.getByRole('button',{name:'Continue',exact:true}).click()
await page.getByRole('button',{name:'Continue',exact:true}).click()
await page.getByRole('button',{name:'Calculate my calories'}).click()
check('Calorie wizard calculates expected default',(await page.locator('main').innerText()).includes('1,682'))
await page.goto(base+'/food-page-analyze/')
await page.getByRole('textbox',{name:'Food page URL'}).fill('invalid')
await page.getByRole('button',{name:'Analyze',exact:true}).click()
check('URL analyzer validates before requesting',(await page.locator('main').innerText()).includes('Invalid URL'))
for(const route of ['/', '/fa/','/fa/calories/','/fa/calories/ghormeh-sabzi/'])for(const width of [320,768,1440]){
 await page.setViewportSize({width,height:900});await page.goto(base+route);await page.evaluate(()=>document.fonts.ready)
 check(`No horizontal overflow ${route} ${width}`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
 if(width!==320)await page.screenshot({path:`${dir}/${route.replace(/[^a-z]+/g,'-')||'home'}-${width}.png`})
}
await page.goto(base+'/fa/')
const faSections=await page.locator('main > section').evaluateAll(elements=>elements.map(e=>e.className))
await page.goto(base+'/')
check('English and Persian use identical section layout',JSON.stringify(faSections)===JSON.stringify(await page.locator('main > section').evaluateAll(elements=>elements.map(e=>e.className))))
await page.locator('.lp-lang select').selectOption('fa')
await page.waitForURL(base+'/fa/')
check('Language switch changes document direction',await page.locator('html').getAttribute('dir')==='rtl')
fs.writeFileSync(`${dir}/interactions.json`,JSON.stringify(checks,null,2))
console.log(`${checks.length} interaction and responsive checks passed`)
await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})
